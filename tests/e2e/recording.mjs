import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';

export async function checkRecording(page,url,artifacts,offline=false){
  const prefix=offline?'offline-':'',requests=[];
  const onRequest=r=>requests.push(r.url());page.on('request',onRequest);
  for(const [width,height]of [[1586,912],[1280,800]]){
    await page.setViewportSize({width,height});
    await page.goto(url+'#view=graph&run=qa-recording&step=2');
    const inspection=page.getByRole('complementary',{name:'Step inspector',exact:true});
    await inspection.locator('.step-meta').getByText('#2',{exact:true}).waitFor();
    await inspection.getByRole('button',{name:'Code Diff',exact:true}).click();
    await inspection.getByLabel('Recorded patch',{exact:true}).waitFor();
    await inspection.locator('.recording-details > summary').click();
    const details=inspection.locator('.recording-details');
    await details.getByText('assistant / tool_call',{exact:true}).waitFor();
    assert.match(await details.innerText(),/2026-01-01T00:00:04Z/);
    assert.match(await details.innerText(),/1 s/);
    assert.match(await details.innerText(),/50 \/ 20/);
    assert.match(await details.innerText(),/Model response ending at this step/);
    await details.scrollIntoViewIfNeeded();
    await page.screenshot({path:join(artifacts,`${prefix}recording-step-${width}.png`),fullPage:true});
    await details.locator('summary').click();
    await inspection.getByLabel('Recorded patch',{exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:join(artifacts,`${prefix}recording-patch-${width}.png`),fullPage:true});
    await page.locator('.run-recording > summary').click();
    const recording=page.getByRole('region',{name:'Recorded session data',exact:true});
    await recording.getByText('4 / 4 steps',{exact:true}).first().waitFor();
    assert.equal(await recording.getByText('4 / 4 steps',{exact:true}).count(),2);
    assert.match(await recording.innerText(),/validate: 1/);
    assert.match(await recording.innerText(),/edit: 1/);
    assert.match(await recording.innerText(),/200/);
    assert.equal(await recording.locator('dd').first().evaluate(el=>getComputedStyle(el).fontSize),'13px');
    assert.equal(await recording.locator('dd small').first().evaluate(el=>getComputedStyle(el).fontSize),'13px');
    await page.screenshot({path:join(artifacts,`${prefix}recording-session-${width}.png`),fullPage:true});
    await recording.getByText('Source messages (2)',{exact:true}).click();
    await recording.locator('summary').filter({hasText:/^user ·/}).click();
    await recording.getByText('Synthetic task.',{exact:true}).waitFor();
    await recording.getByText('Synthetic task.',{exact:true}).scrollIntoViewIfNeeded();
    const messageStyle=await recording.getByText('Synthetic task.',{exact:true}).evaluate(el=>{const s=getComputedStyle(el);return{size:s.fontSize,font:s.fontFamily};});
    assert.equal(messageStyle.size,'15px');assert.match(messageStyle.font,/JetBrains Mono/);
    assert.ok(await recording.locator('p.mono').first().evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Long source references must wrap within recording details');
    await page.screenshot({path:join(artifacts,`${prefix}recording-messages-${width}.png`),fullPage:true});
    const download=page.waitForEvent('download');
    await recording.getByRole('button',{name:'Download recorded source',exact:true}).click();
    const source=await download;
    assert.equal(source.suggestedFilename(),'qa-recording-recorded-source.jsonl');
    const records=readFileSync(await source.path(),'utf8').trim().split('\n').map(line=>JSON.parse(line));
    assert.equal(records.length,13);
    assert.ok(records.some(record=>record.payload?.role==='user'&&record.payload.content[0].text==='Synthetic task.'));
    assert.ok(records.some(record=>record.payload?.input?.includes('tools.apply_patch(patch)')));
    await page.locator('.run-recording > summary').click();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  }
  await page.getByRole('navigation',{name:'Workspace',exact:true}).getByRole('button',{name:'Trajectory replay',exact:true}).click();
  await page.getByRole('button',{name:'Diff',exact:true}).click();
  await page.getByLabel('Recorded patch',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Next replay step',exact:true}).click();
  await page.locator('.recorded-code').getByText('No patch recorded',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Diff',exact:true}).getAttribute('aria-pressed'),'true');
  assert.equal(new URLSearchParams(new URL(page.url()).hash.slice(1)).get('step'),'3');
  await page.goto(url+'#view=timeline&run=qa-recording&step=1');
  await page.getByRole('heading',{name:'Execution Timeline',exact:true}).waitFor();
  const showInspection=page.getByRole('button',{name:'Show inspection',exact:true});
  if(await showInspection.isVisible())await showInspection.click();
  await page.getByRole('complementary',{name:'Step inspector',exact:true}).locator('.step-meta').getByText('#1',{exact:true}).waitFor();
  assert.equal(new URLSearchParams(new URL(page.url()).hash.slice(1)).get('step'),'1');
  if(offline)assert.equal(requests.filter(url=>/^https?:/.test(url)).length,0);
  page.off('request',onRequest);
  return{literalPatch:true,timestamps:true,sourceRoles:true,phases:true,responseTokens:true,callInterval:true,sourceDownload:true,pinnedDiff:true,timelineSource:true,recordingTypography:true,sourceReferenceWrap:true,offline};
}
